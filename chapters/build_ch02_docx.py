def _font(run, size=14, bold=False, italic=False, name=FONT):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)
    rFonts.set(qn("w:eastAsia"), FONT)
    rFonts.set(qn("w:cs"), name)


def _fmt_par(p, *, first=True, align="justify", space_after=0, space_before=0):
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    pf.first_line_indent = Cm(1.0) if first else Cm(0)
    pf.alignment = {
        "justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "left": WD_ALIGN_PARAGRAPH.LEFT,
        "right": WD_ALIGN_PARAGRAPH.RIGHT,
    }[align]


def add_runs(p, text, size=14, bold=False, italic=False, name=FONT):
    run = p.add_run(text)
    _font(run, size=size, bold=bold, italic=italic, name=name)
    return run


def add_p(doc, text, *, first=True, align="justify", size=14, bold=False, italic=False,
          space_after=0, space_before=0):
    p = doc.add_paragraph()
    _fmt_par(p, first=first, align=align, space_after=space_after, space_before=space_before)
    add_runs(p, text, size=size, bold=bold, italic=italic)
    return p


def add_mixed(doc, parts, *, first=True, align="justify"):
    p = doc.add_paragraph()
    _fmt_par(p, first=first, align=align)
    for item in parts:
        text, bold, italic = item[0], item[1], item[2]
        name = item[3] if len(item) > 3 else FONT
        size = item[4] if len(item) > 4 else 14
        add_runs(p, text, size=size, bold=bold, italic=italic, name=name)
    return p


def add_h(doc, text, *, level=1):
    p = doc.add_paragraph()
    align = "center" if level == 1 else "left"
    _fmt_par(p, first=False, align=align, space_before=12, space_after=6)
    add_runs(p, text, bold=True)
    return p


def set_cell_text(cell, text, *, bold=False, size=11):
    cell.text = ""
    p = cell.paragraphs[0]
    _fmt_par(p, first=False, align="center")
    add_runs(p, text, size=size, bold=bold)


def add_table(doc, headers, rows, caption):
    cap = doc.add_paragraph()
    _fmt_par(cap, first=False, align="center", space_before=8, space_after=4)
    add_runs(cap, caption, italic=True)
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.autofit = True
    for j, h in enumerate(headers):
        set_cell_text(table.rows[0].cells[j], h, bold=True)
    for i, row in enumerate(rows, start=1):
        for j, val in enumerate(row):
            set_cell_text(table.rows[i].cells[j], val)
    p = doc.add_paragraph()
    _fmt_par(p, first=False, space_after=6)
    return table


def add_page_numbers(doc):
    section = doc.sections[0]
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    _font(run, size=12)
    fld1 = OxmlElement("w:fldChar")
    fld1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld2 = OxmlElement("w:fldChar")
    fld2.set(qn("w:fldCharType"), "end")
    run._r.append(fld1)
    run._r.append(instr)
    run._r.append(fld2)


def add_query(doc, n, text):
    p = doc.add_paragraph()
    _fmt_par(p, first=False, align="left")
    add_runs(p, f"{n}. ")
    add_runs(p, text, name="Courier New", size=12)
    return p


